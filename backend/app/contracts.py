from __future__ import annotations
from datetime import datetime
from typing import Any, Protocol


class FarmRecordPort(Protocol):
    def persist_observation(self, payload: dict) -> dict: ...
    def persist_estimate(self, payload: dict) -> dict: ...
    def get_crop_context(self, farm_id: str, crop_id: str, planting_id: str | None = None) -> dict: ...
    def list_active_plantings(self, farm_id: str | None = None, crop_id: str | None = None) -> list[dict]: ...
    def list_observations_in_window(
        self, farm_id: str, crop_id: str | None, window_start: datetime, window_end: datetime
    ) -> list[dict]: ...
    def get_observation(self, observation_id: str) -> dict | None: ...
    def get_estimate(self, estimate_id: str) -> dict | None: ...
    def list_estimates(self, farm_id: str | None = None, crop_id: str | None = None, period: str | None = None) -> list[dict]: ...
    def record_actual_harvest(self, payload: dict, actor_id: str) -> dict: ...
    def get_harvest_record(self, farm_id: str, crop_id: str, period: str) -> list[dict]: ...
    def get_actual_by_id(self, actual_harvest_id: str) -> dict | None: ...
    def get_member(self, member_id: str) -> dict | None: ...
    def list_members(self) -> list[dict]: ...
    def list_farms(self) -> list[dict]: ...
    def list_crops(self) -> list[dict]: ...


class Predictor(Protocol):
    model_version: str
    training_provenance: dict

    def predict(self, input_data: dict) -> dict[str, Any]: ...


class HarvestPredictionPort(Protocol):
    def generate(self, data: dict, principal: Any = None, *, trigger: str = "manual") -> dict: ...
    def get(self, prediction_id: str, principal: Any) -> dict: ...
    def get_by_id(self, prediction_id: str) -> dict | None: ...
    def latest_for_scope(self, farm_id: str, crop_id: str, period: str) -> dict | None: ...
    def list_for_scope(self, farm_id: str | None = None, crop_id: str | None = None, period: str | None = None) -> list[dict]: ...
    def get_state(self, farm_id: str, crop_id: str, period: str) -> dict | None: ...


class SupplyCoordinationPort(Protocol):
    def approved_availability(self, period: str) -> list[dict]: ...
    def member_approved_availability(self, period: str, member_id: str | None = None) -> list[dict]: ...
    def get_availability(self, availability_id: str) -> Any: ...
    def lock_availability_for_selection(self, availability_id: str) -> Any: ...
    def list_adjustments(self, period: str) -> list[dict]: ...
